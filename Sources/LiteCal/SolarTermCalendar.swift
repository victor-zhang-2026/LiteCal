    static func name(for day: CivilDate) -> String? {
        guard (1901...2100).contains(day.year), (1...12).contains(day.month) else { return nil }
        let row = Array(dates[day.year - 1901].utf8)
        let firstIndex = (day.month - 1) * 4
        for term in 0..<2 {
            let offset = firstIndex + term * 2
            let date = Int(row[offset] - 48) * 10 + Int(row[offset + 1] - 48)
            if day.day == date { return names[(day.month - 1) * 2 + term] }
        }
        return nil
    }
